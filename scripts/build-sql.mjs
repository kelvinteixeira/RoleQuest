#!/usr/bin/env node
/**
 * Builds the one-paste SQL scripts from supabase/migrations/*.sql:
 * - supabase/setup.sql: every migration, in order (a new database);
 * - supabase/pending.sql: only the latest migration (a database that is one behind).
 * Both run in one transaction: if anything fails, nothing is applied.
 *
 * Usage: node scripts/build-sql.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "supabase/migrations";
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

const section = (file) => `-- ===== ${file} =====\n\n${readFileSync(join(dir, file), "utf8").replace(/\r\n/g, "\n").trimEnd()}\n`;
const script = (title, list) =>
  [
    `-- Role Quest — ${title}`,
    "-- Paste into Supabase → SQL Editor → Run. Atomic: if anything fails, nothing is applied.",
    "-- Generated by scripts/build-sql.mjs from supabase/migrations/*.sql — edit those, not this file.",
    "",
    "begin;",
    "",
    list.map(section).join("\n\n"),
    "",
    "commit;",
    "",
  ].join("\n");

const latest = files.at(-1);
writeFileSync("supabase/setup.sql", script(`full setup in one script (all ${files.length} migrations, in order).`, files));
writeFileSync("supabase/pending.sql", script(`latest migration only (${latest}).`, [latest]));
console.log(`setup.sql: ${files.length} migrations · pending.sql: ${latest}`);
